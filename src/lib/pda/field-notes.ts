const AREA_RADIUS: Record<string, string> = {
  star: "How big the sun is, in solar radii. It does not move planets. Use the habitable bands for orbit distance. Example: 1",
  territory: "How far this faction’s sphere reaches, in light years. Example: 75",
  general: "Size of the whole galaxy in light years, from the center. Example: 100",
};

export function noteForField(label: string, area?: string): string {
  const key = label.trim();
  if (key === "Radius" && area && AREA_RADIUS[area]) return AREA_RADIUS[area];
  if (/^Option \d+$/i.test(key)) {
    return "A player reply. Type the line, or a Localization.csv key such as txt_Yes. Next state is where that reply goes. Example: I'll take it.";
  }
  const direct = NOTES[key];
  if (direct) return direct;
  const folded = Object.keys(NOTES).find((name) => name.toLowerCase() === key.toLowerCase());
  if (folded) return NOTES[folded]!;
  return fallbackNote(key);
}

function fallbackNote(label: string): string {
  if (/color/i.test(label)) return `${label} is red, green, blue from 0 to 1. Example: 1, 0.8, 0.2`;
  if (/^(is|allow|hidden|drop|use|can)/i.test(label)) return `${label} is on or off. Example: True`;
  if (/english|german|french|spanish|russian|polish|italian|portuguese|chinese|japanese|korean|turkish|hungarian|romanian|czech|ukrainian/i.test(label)) {
    return `The ${label} line players read. Color tags work. Example: [cfc020]Ready[-]`;
  }
  if (/price|cost|count|amount|size|mass|volume|health|hit|durability|time|delay|level|radius|range|factor|weight|prob|stack/i.test(label)) {
    return `${label} is a number. A span is two numbers. Example: 10 or 5, 20`;
  }
  if (/icon/i.test(label)) return `${label} is a file name with no folder. Example: Core_T1`;
  if (/list|items|loot/i.test(label)) return `${label} is a comma-separated list. Example: IronIngot, CopperIngot`;
  return `${label} is stored as ${label}: value. Numbers and True or False stay bare. Text with a space or comma uses quotes. Example: 10 or "Core Armor"`;
}
